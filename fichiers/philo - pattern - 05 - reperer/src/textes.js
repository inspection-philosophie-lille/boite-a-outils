window.appConfig = {
	// Fonction pour obtenir une classe CSS pour une catégorie
	getColorClassForCategory: function(category) {
		return `color-highlight-${category.replace(/'/g, '')}`;
	},
	
	// Fonction pour obtenir une classe CSS pour la liste
	getListColorClassForCategory: function(category) {
		return `connector-category-${category.replace(/'/g, '')}`;
	},
	
	// Fonction pour obtenir la couleur d'une catégorie
	getCategoryColor: function(category) {
		return window.textData.categoryColors[category] || '#FFFF00';
	},
	
	// Fonction pour formater le titre pour mobile
	formatTitleForMobile: function() {
		const titleElement = document.getElementById('mobileTitle');
		const screenWidth = window.innerWidth;
		const messages = window.textData?.messages?.titles || {};
		
		if (screenWidth <= 400) {
			titleElement.innerHTML = messages.main || 'repérer les connecteurs logiques';
			titleElement.style.whiteSpace = 'nowrap';
			titleElement.style.overflow = 'hidden';
			titleElement.style.textOverflow = 'ellipsis';
		} else if (screenWidth <= 768) {
			titleElement.innerHTML = (messages.main || 'repérer les connecteurs logiques').replace(' ', '<br>');
			titleElement.style.whiteSpace = 'normal';
			titleElement.style.overflow = 'visible';
			titleElement.style.textOverflow = 'clip';
		} else {
			titleElement.innerHTML = messages.main || 'repérer les connecteurs logiques';
			titleElement.style.whiteSpace = 'nowrap';
		}
	},
	
	// Fonction pour obtenir le nom d'une couleur à partir de son code hexadécimal
	getColorName: function(hexColor) {
		const colorMap = {
			'#FFFF00': 'color-yellow',
			'#FFDF00': 'color-gold',
			'#FF0000': 'color-red',
			'#2DDFF3': 'color-turquoise',
			'#F75B14': 'color-orange',
			'#00ff00': 'color-green'
		};
		return colorMap[hexColor] || 'color-yellow';
	},
	
	// Fonction pour nettoyer une expression (enlever la ponctuation)
	cleanExpression: function(expression) {
		return expression.replace(/[.,!?;:()'"«»]/g, '').trim();
	},
	
	// Fonction pour normaliser un mot (minuscules, sans accents)
	normalizeWord: function(word) {
		if (!word) return '';
		return word.toLowerCase()
			.normalize('NFD')
			.replace(/[\u0300-\u036f]/g, '')
			.replace(/[.,!?;:()'"«»]/g, '')
			.trim();
	},
	
	// Fonction pour normaliser un mot en gardant les accents
	normalizeWordKeepAccents: function(word) {
		if (!word) return '';
		return word.toLowerCase().trim();
	},
	
	// Fonction pour enlever les balises HTML d'un texte
	stripHTML: function(text) {
		if (!text) return '';
		return text.replace(/<[^>]*>/g, '');
	},
	
	// Fonction pour obtenir la catégorie d'un connecteur
	getConnectorCategory: function(connectorText) {
		if (!window.connecteursData || !window.connecteursData.connecteurs) {
			return null;
		}
		
		const normalizedText = this.normalizeWord(connectorText);
		
		for (const [category, connectors] of Object.entries(window.connecteursData.connecteurs)) {
			for (const connector of connectors) {
				const normalizedConnector = this.normalizeWord(connector);
				if (normalizedText === normalizedConnector) {
					return category;
				}
				// Pour les connecteurs composés de plusieurs mots
				if (connector.includes(' ')) {
					const words = connector.toLowerCase().split(' ');
					for (const word of words) {
						if (normalizedText === this.normalizeWord(word)) {
							return category;
						}
					}
				}
			}
		}
		return null;
	}
};

